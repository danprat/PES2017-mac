#!/usr/bin/env python3
"""Generate runtime/pes_r1_probes.cpp: a GUEST_HOOK per function reachable by direct
calls (bl) from ROOT, DEPTH levels deep, that logs when the function returns with r1
not restored (a recompiled function that unbalances the guest stack).
usage: tools/gen_r1_probes.py ROOT [DEPTH=3] [EXCLUDE,...]   (hex addresses)"""
import glob, re, sys
root = sys.argv[1].upper(); depth = int(sys.argv[2]) if len(sys.argv) > 2 else 3
exclude = set(a.upper() for a in sys.argv[3].split(',')) if len(sys.argv) > 3 else set()
bodies = {}
for f in glob.glob('ppc/ppc_recomp.*.cpp'):
    cur = None
    for line in open(f):
        m = re.match(r'PPC_FUNC_IMPL\(__imp__sub_([0-9A-F]+)\)', line)
        if m: cur = m.group(1); bodies[cur] = []; continue
        if cur:
            m = re.match(r'\t// bl? 0x([0-9a-f]+)$', line.rstrip())
            if m: bodies[cur].append(m.group(1).upper())
seen, frontier = {root}, [root]
for _ in range(depth):
    nxt = []
    for fn in frontier:
        for c in bodies.get(fn, []):
            if c in bodies and c not in seen: seen.add(c); nxt.append(c)
    frontier = nxt
# CRT prologue/epilogue helpers (__savegprlr etc.) are not real functions.
helpers = {c for c in seen if not bodies.get(c) and c not in (root,)}
# Functions another runtime file hooks already would be defined twice.
for f in glob.glob('runtime/**/*.cpp', recursive=True):
    if f.endswith('pes_r1_probes.cpp'): continue
    exclude |= set(m.upper() for m in re.findall(r'GUEST_HOOK\(([0-9A-Fa-f]{8})\)', open(f).read()))
targets = sorted(seen - exclude)
with open('runtime/pes_r1_probes.cpp', 'w') as o:
    o.write('// Generated by tools/gen_r1_probes.py %s %d: r1 balance probes. Temporary.\n' % (root, depth))
    o.write('#include <ppc_recomp_shared.h>\n#include "title.h"\n#include "log.h"\n#include "crash.h"\n#include <atomic>\n\n')
    o.write('#define R1_PROBE(a) GUEST_HOOK(a) { const uint32_t sp = ctx.r1.u32; const uint32_t lr = uint32_t(ctx.lr); GUEST_ORIG(a)(ctx, base); \\\n'
            '    if (ctx.r1.u32 != sp) { static std::atomic<int> told{0}; if (told++ < 3) LOGW("r1probe: sub_" #a " (from %08X) moved r1 %08X -> %08X on \'%s\'", lr, sp, ctx.r1.u32, crash::CurrentThreadName()); } }\n\n')
    for t in targets: o.write('R1_PROBE(%s)\n' % t)
print(len(targets), 'probes')
